/**
 * Safe translation lookup function with reliable fallback to default language (en).
 *
 * @param {string} section - Dictionary section ('navigation', 'upload', 'medassist', 'voice')
 * @param {string} key - Translation key
 * @param {string} lang - Active language code ('en', 'ta', 'hi', 'te')
 * @returns {string} Translated string or fallback English string
 */
export function getTranslation(section, key, lang = DEFAULT_LANGUAGE) {
  const targetLang = SUPPORTED_LANGUAGES[lang] ? lang : DEFAULT_LANGUAGE;
  const sectionDict = TRANSLATIONS[section];

  if (!sectionDict) {
    return key;
  }

  // Attempt active language
  if (sectionDict[targetLang] && sectionDict[targetLang][key] !== undefined) {
    return sectionDict[targetLang][key];
  }

  // Fallback to default language
  if (sectionDict[DEFAULT_LANGUAGE] && sectionDict[DEFAULT_LANGUAGE][key] !== undefined) {
    return sectionDict[DEFAULT_LANGUAGE][key];
  }

  // Last-resort fallback to raw key
  return key;
}
